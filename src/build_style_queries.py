def main():
    rows = [json.loads(l) for l in open(SRC, encoding="utf-8") if l.strip()]

    # 实体 -> 它的关键词与英文名（保证聚合仍归到同一个导演）
    meta = {}
    for r in rows:
        zh = r.get("director_zh")
        if not zh:
            continue
        m = meta.setdefault(zh, {"en": r.get("director"), "kw": [],
                                 "domain": r.get("domain"),
                                 "facet": r.get("facet")})
        for w in (r.get("kw_zh") or []):
            if w not in m["kw"]:
                m["kw"].append(w)

    added, missing = [], []
    for zh, sents in QUERIES.items():
        m = meta.get(zh)
        if not m:
            missing.append(zh)
            continue
        for i, s in enumerate(sents, 1):
            added.append({
                "doc_id": f"q{len(added)+1:04d}",
                "kind": "style_query",
                "director": m["en"],
                "director_zh": zh,
                "kw_zh": m["kw"][:6],
                # 必须写 prompt_video：这些句子是给"视频请求"用的。
                # 第一版从实体第一条文档抄 domain，结果 63 条全成了 prompt_image，
                # 视频域检索把它们全过滤掉，命中率一点没变（20/63 -> 20/63）。
                "domain": "prompt_video",
                "facet": m["facet"] or "",
                "text_semantic": s,          # 只放人话，不掺名字
                "description": f"{zh} 的常见请求：{s}",
            })

    with open(OUT, "w", encoding="utf-8") as f:
        for r in rows + added:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"  语料 {len(rows)} -> {len(rows) + len(added)}  (+{len(added)} 条查询侧文档)")
    print(f"  覆盖 {len(QUERIES) - len(missing)} 个风格")
    if missing:
        print(f"  ⚠️ 语料里没有这些实体：{missing}")
    print("\n### STYLE_QUERY_DONE")


if __name__ == "__main__":
    main()
