def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    docs, queries = [], []
    seen = set()
    n = 0

    for (en, zh, country, era, sig, scenes, kws) in D:
        if en in seen:
            continue
        seen.add(en)
        n += 1
        doc_ids = []
        for si, scene in enumerate(scenes):
            is_video = (si == 2)
            ar = "21:9" if is_video else "2.35:1"
            params = {"ar": ar, "style": "raw"}
            tail = "--v 6 --style raw" if not is_video else "--v 6 --duration 5s"
            description = f"{scene}, {sig}"
            kind = "video" if is_video else "still"
            prompt = f"cinematic {kind}, {description}, in the style of {en}, 35mm film, --ar {ar} {tail}"
            doc_id = f"d{n:03d}_{si}"
            doc_ids.append(doc_id)
            docs.append({
                "doc_id": doc_id,
                "domain": "prompt_video" if is_video else "prompt_image",
                "lang": "en",
                "director": en,
                "director_zh": zh,
                "country": country,
                "era": era,
                "style_tags": [k.strip() for k in sig.split(",")][:6],
                "kw_zh": kws,          # 中文风格词：只给 query 用，绝不进 doc 文本
                "description": description,
                # 语义字段 = 描述 + 导演名，但排除参数
                # （实测参数占 43% token，必须隔离；但名字是真实文档内容的一部分，应保留）
                "text_semantic": f"{description}, in the style of {en}",
                "params": params,
                "prompt": prompt,
            })
        kw = "、".join(kws)
        queries.append({
            "query_id": f"q{n:03d}",
            "query": f"想要那种{kw}的感觉，像{zh}的电影，提示词怎么写",
            "lang": "zh",
            "domain": "prompt_image",
            "relevant": doc_ids,
            "target_director": en,
        })

    p1 = os.path.join(OUT_DIR, "prompt_director.jsonl")
    p2 = os.path.join(OUT_DIR, "query_director.jsonl")
    with open(p1, "w", encoding="utf-8") as f:
        for d in docs:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")
    with open(p2, "w", encoding="utf-8") as f:
        for q in queries:
            f.write(json.dumps(q, ensure_ascii=False) + "\n")

    print(f"directors : {n}")
    print(f"docs      : {len(docs)}  -> {p1}")
    print(f"queries   : {len(queries)} -> {p2}")
    plens = [len(d["prompt"]) for d in docs]
    print(f"prompt 长度: 平均 {statistics.mean(plens):.0f} 字符, 最长 {max(plens)}")


if __name__ == "__main__":
    main()
